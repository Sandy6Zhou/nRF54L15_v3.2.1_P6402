#ifndef _MY_BATTERY_H_
#define _MY_BATTERY_H_

// 电池状态枚举, 定义了电池的不同状态等级，从空到满
typedef enum
{
    BATT_UNKNOWN = -1,  /* 电池状态未知状态 */
    BATT_EMPTY,         /* 电池电量为空 */
    BATT_LOW,           /* 电池电量低 */
    BATT_NORMAL,        /* 电池电量正常 */
    BATT_FAIR,          /* 电池电量良好 */
    BATT_HIGH,          /* 电池电量高 */
    BATT_FULL,          /* 电池电量满 */
} my_batt_state_t;

// 电源状态枚举, 定义了设备的电源连接状态
typedef enum
{
    CHARG_UNKNOWN = -1,     /* 充电状态未知状态 */
    NO_CHARGING,            /* 充电器未连接 */
    CHARGING,               /* 充电器已连接（充电中） */
    CHARG_FULL,             /* 充电器已连接且电池已充满 */
} my_chg_state_t;

typedef enum
{
    CHG_BATT_LOW,    /* 充电状态电池电量低 */
    CHG_BATT_FAIR,   /* 充电状态电池电量良好 */
    CHG_BATT_HIGH,   /* 充电状态电池电量高 */
    CHG_BATT_FULL,   /* 充电状态电池电量满，电池已充满 */
} my_chg_batt_state_t;

// LED模式枚举, 定义了LED的不同显示模式
typedef enum
{
    BATT_LED_MODE,          // 电池状态LED模式
    CHG_LED_MODE,           // 充电状态LED模式
    BT_RADIO_LED_MODE,      // 蓝牙广播状态LED模式
    BT_CONNECT_LED_MODE,    // 蓝牙连接状态LED模式
} led_mode_t;

//电池电压-电量映射结构体,用于存储电池电压值与对应电量百分比的映射关系,用于通过电池电压计算电量百分比.
typedef struct
{
    int32_t mv;       /**< 电池电压值，单位为毫伏 (mV) */
    int8_t percent;   /**< 对应的电池电量百分比，范围为 0-100 */
} batt_volt_percent_map_t;

// LED控制上下文结构体, 用于存储LED控制相关的状态信息
typedef struct
{
  uint8_t led_status;                // LED控制标志位
  led_mode_t active_mode;            // 当前生效模式
  uint8_t led_count;                 // LED计数器
} led_ctrl_ctx_t;

// 电源状态，初始值为未连接
extern my_chg_state_t g_charg_state;

int batt_read_mv(int32_t *mv);
int ntc_read_raw(int16_t *raw);
int batt_adc_init(void);
void batt_enable(bool on);
int batt_gpio_init(void);

/*********************************************************************
**函数名称:  my_battery_update_state
**入口参数:  无
**出口参数:  无
**函数功能:  检查并更新电池状态
*********************************************************************/
void my_battery_update_state(void);

/*********************************************************************
**函数名称:  my_battery_show_chgled
**入口参数:  无
**出口参数:  无
**函数功能:  检查充电检测引脚的状态，根据检测结果更新充电状态并控制LED显示。
** 如果检测到充电，则启动充电LED控制定时器；如果未检测到充电，则关闭所有电池LED。
*********************************************************************/
void my_battery_show_chgled();

/*********************************************************************
**函数名称:  my_battery_read_mv
**入口参数:  *mv  --  指向存储电池电压值的指针，单位为毫伏
**出口参数:  err  --  错误码，0 表示成功，非 0 表示失败
**函数功能:  读取电池电压值（毫伏）,函数采用多次采样并去除极值的方法提高测量准确性,
**           最终结果会乘以 2，是因为硬件电路中的分压系数
*********************************************************************/
int my_battery_read_mv(int32_t *mv);

/*********************************************************************
**函数名称:  my_battery_pm_register
**入口参数:  无
**出口参数:  无
**函数功能:  将 Battery 模块注册到统一 PM 框架
**返 回 值:  0 表示成功，负值表示失败
*********************************************************************/
int my_battery_pm_register(void);

/*********************************************************************
**函数名称:  get_show_percent
**入口参数:  无
**出口参数:  电池电量百分比
**函数功能:  获取当前电池电量百分比
*********************************************************************/
int8_t get_show_percent(void);

/*********************************************************************
**函数名称:  get_charge_state_level
**入口参数:  无
**出口参数:  充电状态引脚电平
**函数功能:  获取当前充电状态引脚电平
*********************************************************************/
int get_charge_state_level(void);

/*********************************************************************
**函数名称:  open_led_timer
**入口参数:  timer_ms: 定时器周期时间，单位毫秒
**出口参数:  无
**函数功能:  打开LED控制开关，用于显示指示灯状态
*********************************************************************/
void open_led_timer(uint32_t timer_ms);

/*********************************************************************
**函数名称:  my_led_ctrl_mode
**入口参数:  无
**出口参数:  无
**函数功能:  控制LED模式
*********************************************************************/
void my_led_ctrl_mode(void);

/*********************************************************************
**函数名称:  led_enable
**入口参数:  on: true=使能，false=禁用
**出口参数:  无
**函数功能:  使能LED
*********************************************************************/
void led_enable(bool on);

/*********************************************************************
**函数名称:  led_set_mode
**入口参数:  mode: LED模式
** on: 是否开启
**出口参数:  无
**函数功能:  设置LED模式
*********************************************************************/
void led_set_mode(led_mode_t mode, bool on);

/*********************************************************************
**函数名称:  led_get_enable
**入口参数:  无
**出口参数:  LED使能标志
**函数功能:  获取LED使能标志
*********************************************************************/
bool led_get_enable(void);

#endif
