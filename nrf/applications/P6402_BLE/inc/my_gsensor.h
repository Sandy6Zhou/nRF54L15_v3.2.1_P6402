#ifndef _MY_GSENSOR_H_
#define _MY_GSENSOR_H_

#define GSENSOR_DUTY_PROJECT 0

/* 智能模式时间间隔定义（单位：秒） */
#define STATIC_INTERVAL         (24 * 60 * 60)   // 静止状态：24小时

/* 智能模式状态枚举 */
typedef enum
{
    STATE_UNKNOWN = 0,      // 未知状态
    STATE_STATIC,           // 静止状态
    STATE_MOTION,           // 运动状态
} gsensor_state_t;

/* ============================================================
 *  IMU原始数据结构: 单个采样点的6轴数据
 * ============================================================ */
typedef struct {
    float acc_x;
    float acc_y;
    float acc_z;                  /* 三轴加速度 (m/s^2) */
    float gyro_x;
    float gyro_y;
    float gyro_z;               /* 三轴角速度 (rad/s) */
} imu_reading_t;

/* GSENSOR 运行时上下文结构体 */
typedef struct
{
    /* 传感器状态 */
    bool sensor_ready;                          // 传感器是否已初始化并就绪

    gsensor_state_t last_gsensor_state;         // 上次上报的运动状态，用于检测状态变化避免重复上报
    gsensor_state_t current_gsensor_state;      // 当前运动状态（静止/运动/未知）
} gsensor_runtime_ctx_t;

extern gsensor_runtime_ctx_t g_gsensor_runtime_ctx;

/********************************************************************
**函数名称:  my_gsensor_init
**入口参数:  tid      ---        指向线程 ID 变量的指针
**出口参数:  tid      ---        存储启动后的线程 ID
**函数功能:  初始化 G-Sensor 相关的 I2C 设备与 GPIO 引脚，并启动 G-Sensor 线程
**返 回 值:  0 表示成功，负值表示失败
*********************************************************************/
int my_gsensor_init(k_tid_t *tid);

/********************************************************************
**函数名称:  my_gsensor_pwr_on
**入口参数:  on       ---        true 开启，false 关闭
**出口参数:  无
**函数功能:  控制 G-Sensor 的电源 (P2.6)
**返 回 值:  0 表示成功
*********************************************************************/
int my_gsensor_pwr_on(bool on);

/********************************************************************
**函数名称:  my_gsensor_read_data
**入口参数:  无
**出口参数:  data     ---        存储读取到的三轴数据
**函数功能:  读取当前加速度传感器的三轴原始数据
**返 回 值:  0 表示成功，负值表示失败
*********************************************************************/
void my_gsensor_read_data(void);

/********************************************************************
**函数名称:  my_bmi325_init
**入口参数:  无
**出口参数:  无
**函数功能:  初始化 BMI325 传感器设备
**返 回 值:  0 表示成功，负值表示失败
*********************************************************************/
int my_bmi325_init(void);

/********************************************************************
**函数名称:  lsm6dsv16x_check_id
**入口参数:  无
**出口参数:  无
**函数功能:  检查 LSM6DSV16X 是否在线
**返 回 值:  true 表示识别成功
*********************************************************************/
bool lsm6dsv16x_check_id(void);

/********************************************************************
**函数名称:  get_chip_id
**入口参数:  无
**出口参数:  无
**函数功能:  获取 LSM6DSV16X 芯片ID
**返 回 值:  LSM6DSV16X 芯片ID
*********************************************************************/
uint8_t get_chip_id(void);

/********************************************************************
**函数名称:  smart_mode_apply_lte_policy
**入口参数:  无
**出口参数:  无
**函数功能:  根据当前运动状态和智能模式子模式参数，重新应用LTE唤醒定时器策略
**返 回 值:  无
**注意事项:  不发送状态切换告警，仅设置LTE电源策略和定时器间隔
*********************************************************************/
void smart_mode_apply_lte_policy(void);

/********************************************************************
**函数名称:  get_motion_status
**入口参数:  无
**出口参数:  无
**函数功能:  获取当前运动状态，发送状态切换告警并应用LTE唤醒策略
**返 回 值:  无
*********************************************************************/
void get_motion_status(void);

/********************************************************************
**函数名称:  my_gsensor_get_state
**入口参数:  无
**出口参数:  无
**函数功能:  获取当前GSENSOR状态
**返 回 值:  当前GSENSOR状态（静止/陆运/海运）
*********************************************************************/
gsensor_state_t my_gsensor_get_state(void);

/********************************************************************
**函数名称:  my_gsensor_save_imu_bias
**入口参数:  无
**出口参数:  无
**函数功能:  保存当前 IMU 偏置值到用户数据存储
**返 回 值:  无
*********************************************************************/
void my_gsensor_save_imu_bias(void);

#endif /* _MY_GSENSOR_H_ */
