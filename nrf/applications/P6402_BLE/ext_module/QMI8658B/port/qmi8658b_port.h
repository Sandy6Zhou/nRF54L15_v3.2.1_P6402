#ifndef _QMI8658B_PORT_H_
#define _QMI8658B_PORT_H_

#include <stdint.h>

#include "../driver/qmi8658b_driver.h"

/********************************************************************
**函数名称:  qmi8658b_port_init
**入口参数:  无
**出口参数:  无
**函数功能:  检查并初始化 I2C 和 INT1 端口资源
**返回值:    0 表示成功，负值表示失败
*********************************************************************/
int qmi8658b_port_init(void);

/********************************************************************
**函数名称:  qmi8658b_port_get_bus
**入口参数:  无
**出口参数:  无
**函数功能:  获取驱动层使用的总线访问接口
**返回值:    成功返回总线接口指针，失败返回 NULL
*********************************************************************/
const qmi8658b_bus_t *qmi8658b_port_get_bus(void);

/********************************************************************
**函数名称:  qmi8658b_port_register_int_callback
**入口参数:  callback ---        INT1 中断回调函数（输入）
**出口参数:  无
**函数功能:  注册 INT1 GPIO 上升沿通知回调
**返回值:    0 表示成功，负值表示失败
*********************************************************************/
int qmi8658b_port_register_int_callback(void (*callback)(void));

#endif /* _QMI8658B_PORT_H_ */
